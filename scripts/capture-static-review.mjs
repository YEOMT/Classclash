import fs from 'node:fs/promises';
import {chromium} from '@playwright/test';
process.env.PLAYWRIGHT_BROWSERS_PATH='C:/Users/jarsc/AppData/Local/ms-playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3122',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
const count=await page.locator('.card').count();
if(count!==18)throw new Error('Expected 18 hero cards');
await page.screenshot({path:'artifacts/asset-static/review-desktop.png',fullPage:false});
await page.locator('#hero').selectOption('archer');
await page.locator('[data-scale="4"]').click();
await page.locator('#background').click();
await page.waitForFunction(()=>document.querySelector('#final').complete && document.querySelector('#final').naturalWidth===64);
if(await page.locator('#name').textContent()!=='궁수')throw new Error('Hero selection failed');
await page.screenshot({path:'artifacts/asset-static/review-archer-light.png'});
await page.locator('[data-scale="1"]').click();
const width=await page.locator('#final').evaluate(el=>el.getBoundingClientRect().width);
if(width!==64)throw new Error('Native-scale preview is not 64px');
await page.locator('#hero').selectOption('pyromancer');
await page.locator('[data-scale="3"]').click();
await page.locator('#background').click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/asset-static/review-mobile.png'});
const broken=await page.locator('img').evaluateAll(imgs=>imgs.filter(x=>!x.complete||!x.naturalWidth).map(x=>x.src));
if(broken.length||errors.length)throw new Error(JSON.stringify({broken,errors}));
const report={heroCards:count,selectionWorks:true,integerZoomWorks:true,backgroundToggleWorks:true,brokenImages:broken,browserErrors:errors,desktop:[1500,1100],mobile:[390,844]};
await fs.writeFile('artifacts/asset-static/browser-validation.json',JSON.stringify(report,null,2));
await browser.close();console.log(JSON.stringify(report));
